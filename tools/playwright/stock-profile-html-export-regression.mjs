import fs from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright";
const base = (process.env.PLAYWRIGHT_BASE_URL ?? "https://n50.nifty50today.co.in/n50").replace(/\/$/, "");
const password = process.env.PLAYWRIGHT_ADMIN_PASSWORD;
if (!password) throw new Error("PLAYWRIGHT_ADMIN_PASSWORD is required");
const output = path.resolve(process.env.PLAYWRIGHT_OUTPUT_DIR ?? "output/playwright/stock-profile-html-export-20260823");
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1920, height: 1080 }, acceptDownloads: true, ignoreHTTPSErrors: true });
const login = await context.request.post(`${base}/auth/session/dev-login`, { data: { identifier: "admin", password } });
if (!login.ok()) throw new Error(`login ${login.status()}`);
const page = await context.newPage();
const errors = [];
const failedResponses = [];
page.on("console", (message) => { if (message.type() === "error" && !/cloudflareinsights|clarity\.ms|Failed to load resource/i.test(message.text())) errors.push(message.text()); });
page.on("response", (response) => { if (response.status() >= 400 && response.url().startsWith(base) && !/analytics\/events/i.test(response.url())) failedResponses.push(`${response.status()} ${response.url()}`); });
await page.goto(`${base}/paper-trading?section=factor-analysis`, { waitUntil: "domcontentloaded", timeout: 90_000 });
await page.getByRole("button", { name: "Download interactive HTML" }).waitFor({ timeout: 90_000 });
if (await page.getByLabel("Stock classification filters").count() !== 1) throw new Error("Paper stock filters missing");
if (await page.getByText("Where this evidence is concentrated", { exact: true }).count() !== 1) throw new Error("Paper distribution missing");
await page.screenshot({ path: path.join(output, "paper-factor-profile-filters-1920x1080.png"), fullPage: true });
const downloadPromise = page.waitForEvent("download");
await page.getByRole("button", { name: "Download interactive HTML" }).click();
const download = await downloadPromise;
const htmlPath = path.join(output, download.suggestedFilename());
await download.saveAs(htmlPath);
const offline = await context.newPage();
await offline.goto(`file://${htmlPath}`);
await offline.getByRole("heading", { name: "Paper Trading Parallel Evidence" }).waitFor();
if (await offline.locator("path.line").count() < 1) throw new Error("Offline parallel lines missing");
await offline.locator("path.line").first().focus();
await offline.screenshot({ path: path.join(output, "paper-parallel-offline-html.png"), fullPage: true });
await page.goto(`${base}/`, { waitUntil: "domcontentloaded", timeout: 90_000 });
await page.getByLabel("Stock classification filters").waitFor({ timeout: 90_000 });
if (await page.locator('[data-stock-pill-symbol] img').count() < 40) throw new Error("Home stock logos missing");
await page.screenshot({ path: path.join(output, "home-logo-filter-1920x1080.png"), fullPage: false });
for (const [route, title] of [["/strategy/rolling-monthly", "Rolling Monthly"], ["/strategy/long-options", "Long-Only Options Router"]]) {
  await page.goto(`${base}${route}`, { waitUntil: "domcontentloaded", timeout: 90_000 });
  await page.getByLabel("Stock classification filters").waitFor({ timeout: 90_000 });
  if (await page.getByText(title, { exact: true }).count() < 1) throw new Error(`${title} missing`);
}
await fs.writeFile(path.join(output, "results.json"), JSON.stringify({ passed: errors.length === 0 && failedResponses.length === 0, consoleErrors: errors, failedResponses, htmlPath }, null, 2));
if (errors.length) throw new Error(`console errors: ${errors.join(" | ")}`);
if (failedResponses.length) throw new Error(`failed first-party responses: ${failedResponses.join(" | ")}`);
await browser.close();
console.log(JSON.stringify({ passed: true, output, htmlPath }));

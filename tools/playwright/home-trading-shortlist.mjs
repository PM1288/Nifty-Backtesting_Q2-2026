import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
const base = process.env.PLAYWRIGHT_BASE_URL ?? 'http://127.0.0.1:15199/n50';
const output = process.env.PLAYWRIGHT_OUTPUT_DIR;
if (!output) throw new Error('Set a new output directory');
await fs.mkdir(output,{recursive:false});
const local = new URL(base).hostname === '127.0.0.1';
const origin = local ? 'http://127.0.0.1:19090' : new URL(base).origin;
const env = await fs.readFile('/home/novius2/trading-stack/.env','utf8');
const password = env.split(/\r?\n/).find(line=>line.startsWith('DEV_LOCAL_AUTH_PASSWORD='))?.split('=').slice(1).join('=').trim().replace(/^['"]|['"]$/g,'');
const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM});
const results=[];
let page;
try {
  const context=await browser.newContext({viewport:{width:1440,height:900}});
  const login=await context.request.post(`${origin}/n50/auth/session/dev-login`,{data:{identifier:'admin',password},headers:{Origin:origin}});
  assert.equal(login.status(),200);
  if(local) await context.addCookies((await context.cookies()).map(c=>({...c,path:'/',secure:false})));
  page=await context.newPage();
  page.on('pageerror', error => console.error('Browser runtime:', error.message));
  await page.goto(base+'/',{waitUntil:'domcontentloaded'});
  const toggle=page.getByTestId('home-trading-toggle');
  await toggle.waitFor({timeout:60000});
  const panel=page.getByTestId('home-trading-sidebar');
  assert.equal(await panel.count(),0); results.push('Collapsed by default');
  await toggle.click(); await panel.waitFor();
  await page.getByLabel('Stock symbol',{exact:true}).fill('RELIANCE');
  await page.getByRole('button',{name:'Add to my list',exact:true}).click();
  await page.getByRole('button',{name:'Remove personal long',exact:true}).first().waitFor();
  results.push('Validated personal addition');
  await page.reload(); await toggle.waitFor(); await toggle.click();
  await page.getByRole('button',{name:'Remove personal long',exact:true}).first().waitFor(); results.push('Personal list survives reload');
  await page.screenshot({path:output+'/desktop-home-shortlist.png',fullPage:false});
  await page.setViewportSize({width:390,height:844});
  const bounds=await panel.boundingBox(); assert(bounds.x>=0 && bounds.x+bounds.width<=391);
  await page.screenshot({path:output+'/mobile-home-shortlist.png',fullPage:false}); results.push('Mobile drawer fits');
  await page.getByLabel('Stock symbol',{exact:true}).focus();
  await page.waitForTimeout(10500); assert(await panel.isVisible()); results.push('Typing focus prevents idle close');
  await page.getByRole('button',{name:'Remove personal long',exact:true}).first().click();
  assert.equal(await page.getByRole('button',{name:'Remove personal long',exact:true}).count(),0); results.push('Personal removal');
  await page.locator('h2').filter({hasText:'Trading shortlist'}).click();
  await page.evaluate(()=>document.activeElement?.blur());
  await page.mouse.move(5,200);
  await page.waitForTimeout(11000); assert.equal(await panel.count(),0); results.push('Closes after 10 idle seconds');
  await toggle.click(); await page.keyboard.press('Escape'); assert.equal(await panel.count(),0); results.push('Escape closes');
  await fs.writeFile(output+'/results.json',JSON.stringify({base,fixture:false,passed:results},null,2));
  console.log(results);
} catch(error) {
  await page?.screenshot({path:output+'/failure.png',fullPage:false}).catch(()=>{});
  await fs.writeFile(output+'/results.json',JSON.stringify({base,passed:results,error:String(error)},null,2));
  throw error;
} finally {await browser.close();}
